import fs from 'node:fs';
import path from 'node:path';
import { PRESET_FIELDS, PRESET_VERSION } from '../js/presets.js';

const root = path.resolve(import.meta.dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');

function controlDefault(field) {
  const escaped = field.controlId.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  if (field.type === 'number') {
    const tag = html.match(new RegExp(`<input\\b[^>]*\\bid="${escaped}"[^>]*>`, 'i'))?.[0];
    const value = tag?.match(/\bvalue="([^"]*)"/i)?.[1];
    if (value === undefined && /^audio-amount-/.test(field.controlId)) return 0;
    if (value === undefined) throw new Error(`Missing default for ${field.controlId}`);
    return Number(value);
  }
  const body = html.match(new RegExp(`<select\\b[^>]*\\bid="${escaped}"[^>]*>([\\s\\S]*?)<\\/select>`, 'i'))?.[1];
  if (!body && /^(audio-source|audio-destination)-/.test(field.controlId)) return field.values[0];
  if (!body) throw new Error(`Missing select for ${field.controlId}`);
  const options = [...body.matchAll(/<option\b([^>]*)\bvalue="([^"]+)"[^>]*>/gi)];
  const selected = options.find((match) => /\bselected\b/i.test(match[1])) ?? options[0];
  if (!selected) throw new Error(`Missing options for ${field.controlId}`);
  return selected[2];
}

function groupFor(key) {
  if (/^(mode|frequency$|carrier|pwm|noiseDetail|wavetable|phaseDepth|frequencyDeviation|scanAngle|signalRender)/.test(key)) return 'carrier';
  if (/^(modSource|luma|edge|localContrast|modulation|modThreshold|modSoftness)/.test(key)) return 'modulation';
  if (/^line(Width|Softness)$/.test(key)) return 'line';
  if (/^(instability|phaseJitter|signalNoise|frequencyDrift|horizontalDrift|verticalDrift|driftRate|timeJitter|lineJitter)/.test(key)) return 'instability';
  if (/^(dropout|lineTear)/.test(key)) return 'failure';
  if (key.startsWith('feedback')) return 'feedback';
  if (/^(colorMode|rgbPhaseOffset)/.test(key)) return 'color';
  if (/^(blackLevel|signalGamma|brightness|contrast|phosphorPersistence)/.test(key)) return 'output';
  if (key.startsWith('lfo')) return 'lfo';
  if (key.startsWith('audio')) return key.startsWith('audioSource') || key.startsWith('audioDestination') || key.startsWith('audioAmount') ? 'matrix' : 'audio';
  return 'other';
}

function title(key) {
  return key.replace(/([a-z0-9])([A-Z])/g, '$1 $2').replace(/^./, (value) => value.toUpperCase());
}

const parameters = PRESET_FIELDS.map((field) => ({
  id: field.key,
  control_id: field.controlId,
  label: title(field.key),
  group: groupFor(field.key),
  type: field.type === 'enum' ? 'choice' : field.integer ? 'integer' : 'double',
  default: controlDefault(field),
  ...(field.type === 'enum' ? { choices: field.values } : { min: field.min, max: field.max }),
  animatable: true,
  preset: true,
  host: true,
}));

const contract = {
  schema: 'broken-fm/parameter-contract',
  version: 1,
  preset_schema_version: PRESET_VERSION,
  time_contract: {
    timeline: 'absolute host timeline time in seconds',
    transport: 'timeline time minus the session-only retrigger origin',
  },
  session_state: ['lfoTriggerTime', 'loadedVideo', 'loadedAudio', 'customWavetable', 'openDialog', 'debugView'],
  deferred: ['videoTimeRemapping', 'webcamInput', 'audioBeatDetection', 'embeddedAudio', 'embeddedWavetable'],
  parameters,
};

const output = path.join(root, 'contracts', 'parameters-v1.json');
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, `${JSON.stringify(contract, null, 2)}\n`);

const cppString = (value) => JSON.stringify(String(value));
const cppIdentifier = (value) => value.replace(/[^a-zA-Z0-9]+(.)/g, (_, next) => next.toUpperCase()).replace(/^./, (first) => first.toUpperCase());
const rows = parameters.map((parameter) => {
  const choice = parameter.type === 'choice';
  const defaultChoice = choice ? parameter.choices.indexOf(parameter.default) : 0;
  const defaultValue = choice ? defaultChoice : parameter.default;
  const minimum = choice ? 0 : parameter.min;
  const maximum = choice ? parameter.choices.length - 1 : parameter.max;
  return `  { ${cppString(parameter.id)}, ${cppString(parameter.label)}, ${cppString(parameter.group)}, ParameterType::${parameter.type === 'double' ? 'Double' : parameter.type === 'integer' ? 'Integer' : 'Choice'}, ${defaultValue}, ${minimum}, ${maximum}, ${cppString(choice ? parameter.choices.join('|') : '')}, ${parameter.animatable} },`;
});
const enumRows = parameters.map((parameter, index) => `  ${cppIdentifier(parameter.id)} = ${index},`).join('\n');
const header = `// Generated by tools/generate-parameter-contract.mjs. Do not edit.\n#pragma once\n#include <array>\n#include <cstddef>\n\nnamespace broken_fm {\n\nenum class ParameterType { Double, Integer, Choice };\nenum class ParameterId : std::size_t {\n${enumRows}\n  Count = ${parameters.length}\n};\nstruct ParameterDescriptor {\n  const char* id;\n  const char* label;\n  const char* group;\n  ParameterType type;\n  double default_value;\n  double minimum;\n  double maximum;\n  const char* choices;\n  bool animatable;\n};\n\ninline constexpr std::array<ParameterDescriptor, ${parameters.length}> kParameterDescriptors{{\n${rows.join('\n')}\n}};\n\n}  // namespace broken_fm\n`;
const headerPath = path.join(root, 'native', 'include', 'broken_fm', 'parameters.generated.hpp');
fs.mkdirSync(path.dirname(headerPath), { recursive: true });
fs.writeFileSync(headerPath, header);
console.log(`Wrote ${path.relative(root, output)} and ${path.relative(root, headerPath)} with ${parameters.length} parameters.`);
