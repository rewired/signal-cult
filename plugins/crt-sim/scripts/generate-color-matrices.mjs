import fs from 'node:fs';
// Derive RGB matrices from published primary/white chromaticities.
// D60 spaces are Bradford-adapted to the D65 working white.
const mul=(a,b)=>a.map(row=>b[0].map((_,j)=>row.reduce((sum,v,k)=>sum+v*b[k][j],0)));
const inverse=a=>{const m=a.map((r,i)=>[...r,...[0,1,2].map(j=>+(i===j))]);for(let i=0;i<3;i++){let k=i;for(let j=i+1;j<3;j++)if(Math.abs(m[j][i])>Math.abs(m[k][i]))k=j;[m[i],m[k]]=[m[k],m[i]];const d=m[i][i];m[i]=m[i].map(v=>v/d);for(let j=0;j<3;j++)if(j!==i){const f=m[j][i];m[j]=m[j].map((v,k)=>v-f*m[i][k]);}}return m.map(r=>r.slice(3));};
const xyz=([x,y])=>[[x/y],[1],[(1-x-y)/y]];
const diagonal=v=>v.map((r,i)=>v.map((_,j)=>i===j?r[0]:0));
const rgb=(p,w)=>{const columns=p.map(([x,y])=>[x,y,1-x-y]);const m=[0,1,2].map(i=>columns.map(c=>c[i]));return mul(m,diagonal(mul(inverse(m),xyz(w))));};
const d65=[.3127,.329],d60=[.32168,.33767];
const spaces=[[[.64,.33],[.30,.60],[.15,.06]],[[.8,.313],[.1682,.9877],[.079,-.1155]],[[.713,.293],[.165,.830],[.128,.044]],[[.708,.292],[.170,.797],[.131,.046]],[[.68,.32],[.265,.69],[.15,.06]],[[.7347,.2653],[0,1],[.0001,-.077]]];
const bradford=[[.8951,.2664,-.1614],[-.7502,1.7135,.0367],[.0389,-.0685,1.0296]];
const source=mul(bradford,xyz(d60)),target=mul(bradford,xyz(d65));
const adapt=mul(inverse(bradford),mul(diagonal(target.map((r,i)=>[r[0]/source[i][0]])),bradford));
const working=rgb(spaces[0],d65);
const transforms=spaces.map((p,i)=>mul(inverse(working),i===2||i===5?mul(adapt,rgb(p,d60)):rgb(p,d65)));
let out='// Generated by scripts/generate-color-matrices.mjs.\n';
for(const [name,matrices] of [['toWorkingGamut',transforms],['fromWorkingGamut',transforms.map(inverse)]]){
 out+=`HD inline vec3 ${name}(vec3 v,int gamut){\n switch(gamut){\n`;
 for(let i=1;i<matrices.length;i++)out+=` case ${i}:return vec3(${matrices[i].map(r=>`dot(v,vec3(${r.map(n=>n.toFixed(10)+'f').join(',')}))`).join(',')});\n`;
 out+=' default:return v;\n }\n}\n';
}
fs.mkdirSync('native/generated',{recursive:true});fs.writeFileSync('native/generated/color-matrices.inc',out);
